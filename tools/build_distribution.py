#!/usr/bin/env python3
"""Build the single-file loadstring distribution from the source module.

The source module is intentionally already self-contained. This build step
adds distribution metadata while preserving the implementation byte-for-byte.
"""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "DracoUI.luau"
OUTPUT = ROOT / "Draco.lua"


def build_text(source: str) -> str:
    if not source.startswith("--!strict\n"):
        raise ValueError("DracoUI.luau must keep --!strict as its first line")
    if "require(" in source or "script." in source:
        raise ValueError("the distribution source must not depend on require() or script paths")
    if not source.rstrip().endswith("return DracoUI"):
        raise ValueError("DracoUI.luau must return the public DracoUI table")

    digest = hashlib.sha256(source.encode("utf-8")).hexdigest()
    metadata = (
        "-- Draco UI Lib single-file distribution.\n"
        "-- Generated by tools/build_distribution.py; edit DracoUI.luau instead.\n"
        f"-- Source SHA-256: {digest}\n"
    )
    return "--!strict\n" + metadata + source[len("--!strict\n") :]


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if Draco.lua is stale")
    args = parser.parse_args()

    source = SOURCE.read_text(encoding="utf-8")
    generated = build_text(source)
    if args.check:
        if not OUTPUT.exists():
            raise SystemExit("Draco.lua is missing; run tools/build_distribution.py")
        current = OUTPUT.read_text(encoding="utf-8")
        if current != generated:
            raise SystemExit("Draco.lua is stale; run tools/build_distribution.py")
        print("Draco.lua is up to date")
    else:
        OUTPUT.write_text(generated, encoding="utf-8", newline="\n")
        print(f"built {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
